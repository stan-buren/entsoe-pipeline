def test_generate_custom_fully_built_config(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Verifies that pre-built checklist templates copy directly with warnings.

    Arrange: Create a temporary custom configuration file.
    Act: Run generation script.
    Assert: Verify the file is written exactly as supplied.
    """
    # Arrange
    config_name = "test_prebuilt_custom"
    mock_config = CustomConfig(active_mode="Custom", config_name=config_name)
    monkeypatch.setattr(
        "entsoe_pipeline.fms_metadata.ingestion.my_entsoe_domains.get_custom_config",
        lambda: mock_config,
    )

    MY_ENTSOE_DOMAINS_CUSTOM_DIR.mkdir(parents=True, exist_ok=True)
    custom_file = MY_ENTSOE_DOMAINS_CUSTOM_DIR / f"{config_name}.yml"

    prebuilt_data = {
        "environments": {
            "IOP": {
                "root_directories": [
                    {
                        "name": "TP_export",
                        "domains": {"Load": {"ActualTotalLoad_6.1.A_r3": True}},
                    }
                ]
            }
        }
    }

    with custom_file.open("w", encoding="utf-8") as f:
        yaml.dump(prebuilt_data, f)

    try:
        # Act
        generate_my_entsoe_domains()

        # Assert
        assert MY_ENTSOE_DOMAINS_YML.exists()
        with MY_ENTSOE_DOMAINS_YML.open(encoding="utf-8") as f:
            content = f.read()
            f.seek(0)
            data = yaml.safe_load(f) or {}

        assert "WARNING: THIS FILE IS AUTOMATICALLY GENERATED" in content
        data.pop("generated_at", None)
        assert data == prebuilt_data

    finally:
        # Clean up temporary test custom file
        if custom_file.exists():
            custom_file.unlink()


def test_unrecognized_config_errors(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Verifies that invalid configuration formats raise explicit ValueErrors.

    Arrange: Create an invalid custom configuration file and mock overview.yml.
    Act / Assert: Verify ValueError is raised.
    """
    # Arrange
    config_name = "test_invalid"
    mock_config = CustomConfig(active_mode="Custom", config_name=config_name)
    monkeypatch.setattr(
        "entsoe_pipeline.fms_metadata.ingestion.my_entsoe_domains.get_custom_config",
        lambda: mock_config,
    )

    MY_ENTSOE_DOMAINS_CUSTOM_DIR.mkdir(parents=True, exist_ok=True)
    custom_file = MY_ENTSOE_DOMAINS_CUSTOM_DIR / f"{config_name}.yml"

    invalid_data = {"unrecognized_key": "some_value"}

    with custom_file.open("w", encoding="utf-8") as f:
        yaml.dump(invalid_data, f)

    mock_overview = tmp_path / "overview.yml"
    with mock_overview.open("w", encoding="utf-8") as f:
        yaml.dump({"environments": {"IOP": {"root_directories": []}}}, f)

    monkeypatch.setattr(
        "entsoe_pipeline.fms_metadata.ingestion.my_entsoe_domains.OVERVIEW_YML",
        mock_overview,
    )

    try:
        # Act & Assert
        with pytest.raises(ValueError, match="Invalid checklist template"):
            generate_my_entsoe_domains()
    finally:
        if custom_file.exists():
            custom_file.unlink()
