def test_generate_default_domains(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Verifies generation under 'Default' mode using fallback or default template.

    Arrange: Set mock config for Default mode.
    Act: Run generation script.
    Assert: Check output checklist exists and contains IOP/Prod with load active.
    """
    # Arrange
    mock_config = CustomConfig(active_mode="Default")
    monkeypatch.setattr(
        "entsoe_pipeline.fms_metadata.ingestion.my_entsoe_domains.get_custom_config",
        lambda: mock_config,
    )

    # Write a mocked default template file to be independent of developer physical overrides
    mock_template = tmp_path / "mock_my_entsoe_default.yml"
    mock_template.write_text(
        "selected_domains:\n  Load:\n    - ActualTotalLoad_6.1.A_r3\n", encoding="utf-8"
    )
    monkeypatch.setattr(
        "entsoe_pipeline.fms_metadata.ingestion.my_entsoe_domains.MY_ENTSOE_DOMAINS_DEFAULT_TEMPLATE_YML",
        mock_template,
    )

    # Clean previous run artifact if any
    if MY_ENTSOE_DOMAINS_YML.exists():
        MY_ENTSOE_DOMAINS_YML.unlink()

    # Act
    generate_my_entsoe_domains()

    # Assert
    assert MY_ENTSOE_DOMAINS_YML.exists(), (
        f"Resulting domains config was not created at {MY_ENTSOE_DOMAINS_YML}"
    )

    with MY_ENTSOE_DOMAINS_YML.open(encoding="utf-8") as f:
        content = f.read()
        f.seek(0)
        data = yaml.safe_load(f) or {}

    assert "WARNING: THIS FILE IS AUTOMATICALLY GENERATED" in content
    assert "environments" in data

    environments = data["environments"]
    assert "IOP" in environments
    assert "Prod" in environments

    # Check popular domain (Load -> ActualTotalLoad_6.1.A_r3) is enabled (True)
    iop_root_dirs = environments["IOP"]["root_directories"]
    tp_export = next(d for d in iop_root_dirs if d["name"] == "TP_export")
    assert tp_export["domains"]["Load"]["ActualTotalLoad_6.1.A_r3"] is True


def test_generate_example_popular_domains(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Verifies generation under 'Example' mode using 'entsoe_popular_domains'.

    Arrange: Set mock config targeting popular domains example.
    Act: Run generation script.
    Assert: Check that popular domains are built correctly.
    """
    # Arrange
    config_name = "entsoe_popular_domains"
    mock_config = CustomConfig(active_mode="Example", config_name=config_name)
    monkeypatch.setattr(
        "entsoe_pipeline.fms_metadata.ingestion.my_entsoe_domains.get_custom_config",
        lambda: mock_config,
    )

    MY_ENTSOE_DOMAINS_EXAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    temp_popular_file = MY_ENTSOE_DOMAINS_EXAMPLES_DIR / f"{config_name}.yml"

    popular_data = {"popular_domains": {"Load": ["ActualTotalLoad_6.1.A_r3"]}}

    with temp_popular_file.open("w", encoding="utf-8") as f:
        yaml.dump(popular_data, f)

    try:
        # Act
        generate_my_entsoe_domains()

        # Assert
        assert MY_ENTSOE_DOMAINS_YML.exists()
        with MY_ENTSOE_DOMAINS_YML.open(encoding="utf-8") as f:
            data = yaml.safe_load(f) or {}

        environments = data["environments"]
        iop_root_dirs = environments["IOP"]["root_directories"]
        tp_export = next(d for d in iop_root_dirs if d["name"] == "TP_export")

        # Load is a popular domain, should have popular subfolders enabled
        assert tp_export["domains"]["Load"]["ActualTotalLoad_6.1.A_r3"] is True
        # Non-popular should be disabled (False)
        assert (
            tp_export["domains"]["Load"].get("ProductionAndGenerationUnits_r3", False)
            is False
        )
    finally:
        if temp_popular_file.exists():
            temp_popular_file.unlink()


